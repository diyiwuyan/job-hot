/**
 * 推断单个招聘条目覆盖的专业大类。
 * @param title 标题（含公司 + 岗位列表）
 * @param summary 摘要（含"岗位：..."）
 * @param tags 标签（首个一般是公司名，含行业）
 * @returns 命中的专业大类 code 数组（可能为空；可能含 'unlimited'）
 */
export function inferMajors(title: string, summary: string, tags: string[]): Major[] {
  const isTalk = tags.includes('宣讲会');

  // 宣讲会条目：标题/摘要里只有公司名 + 学校名 + 地点，没有岗位信息，
  // 学校名（如"科技师范大学""药科大学"）会污染专业推断。
  // 因此宣讲会只用行业 tag（去掉学校名）推断，不扫描标题/摘要正文。
  let haystack: string;
  if (isTalk) {
    // tags[0]=宣讲会, 通常含公司名/行业；过滤掉明显是学校/城市的 tag（含"大学/学院/学校"）
    const cleanTags = tags.filter(t => !/大学|学院|学校/.test(t));
    haystack = cleanTags.join(' ');
  } else {
    haystack = `${title} ${summary} ${tags.join(' ')}`;
  }

  const result = new Set<Major>();

  for (const [major, keywords] of Object.entries(MAJOR_KEYWORDS) as [Major, string[]][]) {
    if (keywords.some(kw => haystack.includes(kw))) {
      result.add(major);
    }
  }

  // 不限专业：严格判定 —— 命中明确"不限专业"文本，或典型通用岗关键词
  if (UNLIMITED_KEYWORDS.some(kw => haystack.includes(kw))) {
    result.add('unlimited');
  }

  return [...result];
}
