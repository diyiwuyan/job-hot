const OPPOSITE: Record<MbtiPole, MbtiPole> = {
  E: 'I', I: 'E', S: 'N', N: 'S', T: 'F', F: 'T', J: 'P', P: 'J',
};

export type MbtiCalculation = {
  code: string;
  scores: Record<MbtiPole, number>;
  dimensions: Array<{
    axis: MbtiAxis;
    left: MbtiPole;
    right: MbtiPole;
    leftPercent: number;
    rightPercent: number;
    selected: MbtiPole;
    clarity: '偏好清晰' | '较接近中线' | '非常接近中线';
  }>;
  borderline: boolean;
};

export function calculateMbti(answers: Record<string, number>): MbtiCalculation {
  const scores: Record<MbtiPole, number> = { E: 0, I: 0, S: 0, N: 0, T: 0, F: 0, J: 0, P: 0 };

  MBTI_QUESTIONS.forEach((question) => {
    const answer = answers[question.id];
    if (!answer) return;
    const strength = answer - 1;
    scores[question.pole] += strength;
    scores[OPPOSITE[question.pole]] += 3 - strength;
  });

  const dimensions = MBTI_AXES.map((axis) => {
    const leftScore = scores[axis.left];
    const rightScore = scores[axis.right];
    const total = leftScore + rightScore || 1;
    const leftPercent = Math.round((leftScore / total) * 100);
    const rightPercent = 100 - leftPercent;
    const gap = Math.abs(leftPercent - rightPercent);
    return {
      axis: axis.key,
      left: axis.left,
      right: axis.right,
      leftPercent,
      rightPercent,
      selected: leftScore >= rightScore ? axis.left : axis.right,
      clarity: gap <= 6 ? '非常接近中线' as const : gap <= 18 ? '较接近中线' as const : '偏好清晰' as const,
    };
  });

  return {
    code: dimensions.map((dimension) => dimension.selected).join(''),
    scores,
    dimensions,
    borderline: dimensions.some((dimension) => dimension.clarity !== '偏好清晰'),
  };
}
